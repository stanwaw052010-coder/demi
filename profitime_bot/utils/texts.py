def format_schedule() -> str:
    """График студии словами, одинаковые подряд идущие дни группируются."""
    lines: list[str] = []
    current: str | None = None
    start_idx = 0

    def flush(end_idx: int) -> None:
        if current is None:
            return
        days = (
            dt.WEEKDAYS_SHORT[start_idx]
            if start_idx == end_idx
            else f"{dt.WEEKDAYS_SHORT[start_idx]}–{dt.WEEKDAYS_SHORT[end_idx]}"
        )
        lines.append(f"   {days}: {current}")

    for idx in range(7):
        hours = config.WORK_HOURS.get(idx)
        label = (
            f"{hours[0].strftime('%H:%M')} – {hours[1].strftime('%H:%M')}"
            if hours
            else "вихідний"
        )
        if current is None:
            current, start_idx = label, idx
        elif label != current:
            flush(idx - 1)
            current, start_idx = label, idx
    flush(6)
    return "\n".join(lines)


def format_rules(rules: tuple[str, ...], bullet: str = "•") -> str:
    """Список правил маркированным списком."""
    return "\n".join(f"{bullet} {rule}" for rule in rules)


def format_numbered(items: tuple[str, ...]) -> str:
    """Нумерованный список — для противопоказаний."""
    return "\n".join(f"<b>{index}.</b> {item}" for index, item in enumerate(items, start=1))


def format_intervals() -> str:
    """
    Интервалы по зонам, сгруппированные по значению.

    Собирается из config.SERVICES_EPILATION — отдельного справочника нет,
    поэтому расхождений между карточкой зоны и этим экраном быть не может.
    """
    grouped: dict[int, list[str]] = {}
    for zone in config.SERVICES_EPILATION.values():
        if zone["group"] != "women":
            continue
        grouped.setdefault(zone["interval_days"], []).append(zone["name"].lower())

    lines: list[str] = []
    for interval in sorted(grouped):
        weeks = round(interval / 7)
        names = ", ".join(sorted(grouped[interval]))
        lines.append(
            f"\n<b>{interval} {dt.plural_days(interval)}</b> "
            f"<i>(≈{weeks} {dt.plural_weeks(weeks)})</i>\n{names}"
        )
    return "\n".join(lines)


def service_title(code: str) -> str:
    """Название услуги по коду. Неизвестный код возвращается как есть."""
    service = config.get_any_service(code)
    return service["name"] if service else code


def format_service_card(code: str) -> str | None:
    """Карточка услуги: цена, пакет, длительность, курс, интервал."""
    service = config.get_any_service(code)
    if service is None:
        return None

    description = ""
    if "short" in service:
        description = f"{service['short']}\n\n"
    elif "zones" in service:
        zone_names = ", ".join(
            config.SERVICES_EPILATION[zone_code]["name"].lower()
            for zone_code in service["zones"]
            if zone_code in config.SERVICES_EPILATION
        )
        description = COMPLEX_CARD_ZONES.format(zones=zone_names)

    package = service["package_price"]
    saving = service["price"] * 5 - package

    return SERVICE_CARD.format(
        name=service["name"],
        description=description,
        E_PRICE=E_PRICE,
        price=service["price"],
        package=package,
        saving=saving,
        currency=config.CURRENCY,
        duration=dt.fmt_duration(service["duration"]),
        sessions=service["sessions"],
        sessions_word=dt.plural_sessions(service["sessions"]),
        interval=service["interval_days"],
        interval_word=dt.plural_days(service["interval_days"]),
        course_total=service["price"] * service["sessions"],
    )


def format_items(codes: list[str], with_prices: bool = True) -> str:
    """Список выбранных услуг для карточек заявки."""
    lines: list[str] = []
    for code in codes:
        service = config.get_any_service(code)
        if service is None:
            continue
        if with_prices:
            lines.append(f"{E_LASER} {service['name']} — {service['price']} {config.CURRENCY}")
        else:
            lines.append(f"{E_LASER} {service['name']}")
    return "\n".join(lines) if lines else f"{E_LASER} Консультація"


def items_total(codes: list[str]) -> int:
    """Сумма за один сеанс по выбранным услугам."""
    total = 0
    for code in codes:
        service = config.get_any_service(code)
        if service is not None:
            total += service["price"]
    return total


def format_price_section(header: str, services: list[dict]) -> str:
    """Секция прайса."""
    lines = [header]
    for service in services:
        lines.append(
            PRICE_LINE.format(
                name=service["name"],
                price=service["price"],
                package=service["package_price"],
                currency=config.CURRENCY,
            )
        )
    return "\n".join(lines)


