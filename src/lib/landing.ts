/**
 * Посадкові сторінки під конкретні пошукові запити.
 *
 * Головна сторінка може претендувати на один основний запит — не більше.
 * Щоб з'явитися за «подолог Вишгород», «педикюр Вишгород», «манікюр
 * Вишгород» і «врослий ніготь», під кожен запит потрібна власна сторінка
 * з власним заголовком, власним текстом і власною мікророзміткою.
 *
 * Тексти тут — не переспів головної. Дублювання Google розпізнає й
 * викидає такі сторінки з видачі, тому кожна відповідає на своє питання.
 * Усі цифри взяті з `priceList` — єдиного джерела цін.
 */

import type { PriceGroup, PriceRow } from "./site";
import { priceList, site } from "./site";

