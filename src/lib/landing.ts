/**
 * Група прайсу за назвою. Якщо групу перейменували в `site.ts` — білд
 * впаде з ясною помилкою, а не мовчки покаже сторінку без цін.
 */
function priceGroup(categoryId: string, title: string): PriceGroup {
  const category = priceList.find((item) => item.id === categoryId);
  const group = category?.groups.find((item) => item.title === title);
  if (!group) {
    throw new Error(`Прайс: у категорії «${categoryId}» немає групи «${title}»`);
  }
  return group;
}

/** Кілька позицій із групи — коли на сторінку потрібна не вся група. */
function pickRows(group: PriceGroup, keys: Array<string | [string, string]>): PriceRow[] {
  return keys.map((key) => {
    const [name, note] = Array.isArray(key) ? key : [key, undefined];
    const row = group.rows.find(
      (item) => item.name === name && (note === undefined || item.note === note),
    );
    if (!row) {
      throw new Error(`Прайс: у групі «${group.title}» немає позиції «${name}»`);
    }
    return row;
  });
}

